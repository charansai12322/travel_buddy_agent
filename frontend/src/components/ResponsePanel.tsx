import React, { useState } from 'react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import { Compass, Copy, Check, RotateCcw, AlertCircle } from 'lucide-react';

interface ResponsePanelProps {
  response: string;
  onClear: () => void;
}

export const ResponsePanel: React.FC<ResponsePanelProps> = ({
  response,
  onClear,
}) => {
  const [copied, setCopied] = useState(false);

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(response);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Fallback
      setCopied(false);
    }
  };

  return (
    <section
      className="w-full max-w-3xl mx-auto mt-8 bg-white rounded-2xl border border-slate-200/90 shadow-sm overflow-hidden animate-in fade-in duration-300"
      aria-labelledby="response-heading"
    >
      {/* Response Header */}
      <div className="bg-slate-50/80 px-5 py-4 border-b border-slate-100 flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2.5">
          <div className="h-8 w-8 rounded-lg bg-blue-100/80 text-blue-700 flex items-center justify-center">
            <Compass className="w-4 h-4" />
          </div>
          <div>
            <h2
              id="response-heading"
              className="text-base font-bold text-slate-900 tracking-tight"
            >
              Travel Buddy's Plan
            </h2>
            <p className="text-xs text-slate-500">
              Generated by Travel Buddy AI Agent
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleCopy}
            type="button"
            className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-700 hover:text-slate-900 bg-white hover:bg-slate-50 border border-slate-200 rounded-lg shadow-2xs transition-colors"
            title="Copy plan to clipboard"
          >
            {copied ? (
              <>
                <Check className="w-3.5 h-3.5 text-emerald-600" />
                <span className="text-emerald-700 font-semibold">Copied!</span>
              </>
            ) : (
              <>
                <Copy className="w-3.5 h-3.5 text-slate-500" />
                <span>Copy</span>
              </>
            )}
          </button>

          <button
            onClick={onClear}
            type="button"
            className="inline-flex items-center gap-1.5 px-3 py-1.5 text-xs font-medium text-slate-600 hover:text-slate-900 bg-white hover:bg-slate-50 border border-slate-200 rounded-lg shadow-2xs transition-colors"
            title="Plan another trip"
          >
            <RotateCcw className="w-3.5 h-3.5 text-slate-500" />
            <span>Plan another trip</span>
          </button>
        </div>
      </div>

      {/* Response Body with Safe Markdown Rendering */}
      <div className="p-5 sm:p-7 overflow-x-auto text-slate-800 text-sm sm:text-base leading-relaxed">
        <div className="markdown-content">
          <ReactMarkdown remarkPlugins={[remarkGfm]}>
            {response}
          </ReactMarkdown>
        </div>
      </div>

      {/* Advisory Note Footer */}
      <div className="bg-slate-50/70 px-5 py-3 border-t border-slate-100 flex items-start gap-2 text-xs text-slate-500">
        <AlertCircle className="w-4 h-4 text-amber-500 shrink-0 mt-0.5" />
        <p>
          Flight prices, schedules, and attraction timings can change. Please verify with official booking providers before finalizing reservations.
        </p>
      </div>
    </section>
  );
};
